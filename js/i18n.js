export function renderStaticText() {
  document.documentElement.lang = {
    en: "en",
    ja: "ja",
    zh: "zh-CN",
  }[state.lang] || "en";

  const navMap = [
    ["home", "navHome"],
    ["day", "navDay"],
    ["places", "navPlaces"],
    ["living", "navLiving"],
    ["safe", "navSafe"],
    ["my", "navMy"],
  ];
  navMap.forEach(([page, key]) => {
    const item = document.querySelector(`.main-nav [data-page="${page}"]`);
    if (item) item.textContent = t(key);
  });
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
    node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
  });
  const assistantInputNode = document.querySelector("#assistantInput");
  if (assistantInputNode) assistantInputNode.placeholder = t("assistantInputPlaceholder");
  const languageSelect = document.querySelector("#languageSelect");
  if (languageSelect) languageSelect.value = state.lang;
}
